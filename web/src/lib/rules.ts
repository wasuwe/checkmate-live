/**
 * หมากที่อยู่กลางกระดาน 5×5 เดินไปช่องที่ห่าง (dr, dc) ได้แบบไหน
 * 'dot' = เดินไปได้, 'ring' = ไปได้เฉพาะตอนกิน, '' = ไปไม่ได้ (dr ติดลบคือไปข้างหน้า)
 */
export function reach(kind: Kind, dr: number, dc: number, game: GameId = 'chess'): 'dot' | 'ring' | '' {
  const a = Math.abs(dr)
  const b = Math.abs(dc)
  if (a === 0 && b === 0) return ''
  const straight = a === 0 || b === 0
  const diagonal = a === b
  switch (kind) {
    case 'R':
      return straight ? 'dot' : ''
    case 'B':
      return diagonal ? 'dot' : ''
    case 'Q':
      return straight || diagonal ? 'dot' : ''
    case 'K':
      return Math.max(a, b) === 1 ? 'dot' : ''
    case 'N':
      return (a === 1 && b === 2) || (a === 2 && b === 1) ? 'dot' : ''
    case 'M':
    case 'F':
      return a === 1 && b === 1 ? 'dot' : ''
    case 'S':
      return (a === 1 && b === 1) || (dr === -1 && dc === 0) ? 'dot' : ''
    case 'H':
      return diagonal ? 'dot' : ''
    case 'C':
      // เบี้ยหมากฮอส: เดินทแยงหน้า 1 ช่อง หรือกระโดดกินไปลงช่องที่ห่าง 2 ช่อง
      if (dr === -1 && b === 1) return 'dot'
      return dr === -2 && b === 2 ? 'ring' : ''
    case 'P':
      // เบี้ยหมากรุกไทยเดินตาแรกได้ช่องเดียว
      if (dc === 0 && (dr === -1 || (dr === -2 && game === 'chess'))) return 'dot'
      return dr === -1 && b === 1 ? 'ring' : ''
  }
}
