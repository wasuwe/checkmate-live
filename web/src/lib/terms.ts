const KEY = 'checkmate.termsAccepted'

/** ผู้ใช้กดยอมรับข้อตกลงแล้วหรือยัง (จำไว้เฉพาะในแท็บนี้) */
export function termsAccepted(): boolean {
  try {
    return sessionStorage.getItem(KEY) === '1'
  } catch {
    return false
  }
}

export function setTermsAccepted(accepted: boolean): void {
  try {
    if (accepted) sessionStorage.setItem(KEY, '1')
    else sessionStorage.removeItem(KEY)
  } catch {
    // จำไม่ได้: ผู้ใช้ติ๊กใหม่ในหน้าสมัครได้
  }
}
